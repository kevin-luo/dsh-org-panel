import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const design = join(root, 'design-assets')
const runtime = join(root, 'src', 'runtime-assets')
const generated = join(root, 'src', 'client-v9', 'generated-assets.ts')

const staffSources = {
  secretary: 'community.png',
  'tech-lead': 'tech-lead.png',
  recruiter: 'recruiter.png',
  developer: 'developer.png',
  pm: 'pm.png',
  platform: 'platform.png',
  researcher: 'researcher.png',
  doc: 'doc.png',
  'search-specialist': 'search-specialist.png',
  'image-creator': 'image-creator.png',
  'video-producer': 'video-producer.png',
  novelist: 'novelist.png',
  'social-editor': 'social-editor.png',
  'data-analyst': 'data-analyst.png',
  growth: 'growth.png',
}

await rm(join(root, 'lib'), { recursive: true, force: true })
await rm(runtime, { recursive: true, force: true })
await mkdir(join(runtime, 'office'), { recursive: true })
await mkdir(join(runtime, 'ui'), { recursive: true })
await mkdir(join(runtime, 'staff'), { recursive: true })

await sharp(join(design, 'office', 'office-hq-base.png'))
  .resize(1200, 720, { fit: 'cover', position: 'centre' })
  .webp({ quality: 72, effort: 6, smartSubsample: true })
  .toFile(join(runtime, 'office', 'office-hq-base.webp'))

await sharp(join(design, 'ui', 'logo-hex.png'))
  .resize(96, 96, { fit: 'contain' })
  .webp({ quality: 78, effort: 6, alphaQuality: 90 })
  .toFile(join(runtime, 'ui', 'logo-hex.webp'))

for (const [staffId, sourceName] of Object.entries(staffSources)) {
  const source = join(design, 'staff', sourceName)
  const target = join(runtime, 'staff', staffId)
  await mkdir(target, { recursive: true })
  await sharp(source)
    .resize(96, 96, { fit: 'cover', position: 'attention' })
    .webp({ quality: 76, effort: 6, alphaQuality: 90 })
    .toFile(join(target, 'thumb.webp'))
  await sharp(source)
    .resize(128, 128, { fit: 'contain', position: 'bottom', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 74, effort: 6, alphaQuality: 90 })
    .toFile(join(target, 'sprite.webp'))
  await sharp(source)
    .resize(384, 384, { fit: 'contain', position: 'bottom', background: { r: 0, g: 0, b: 0, alpha: 0 }, withoutEnlargement: true })
    .webp({ quality: 70, effort: 6, alphaQuality: 88 })
    .toFile(join(target, 'profile.webp'))
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) files.push(...await walk(full))
    else files.push(full)
  }
  return files
}

const files = (await walk(runtime)).sort()
const entries = []
for (const file of files) {
  const key = relative(runtime, file).split('\\').join('/')
  const encoded = (await readFile(file)).toString('base64')
  entries.push(`  ${JSON.stringify(key)}: ${JSON.stringify(`data:image/webp;base64,${encoded}`)},`)
}

await writeFile(generated, [
  '// Generated by scripts/build-runtime-assets.mjs. Do not edit by hand.',
  'export const RUNTIME_ASSETS: Record<string, string> = {',
  ...entries,
  '}',
  '',
].join('\n'))

console.log(`Built ${files.length} WebP runtime assets and ${relative(root, generated)}.`)
